-- Baseline: the 4 analytics tables exactly as Hibernate (ddl-auto: update) created them before Flyway
-- (same columns, column order, types, identity ids and primary key names).
-- A database made before Flyway already has them: it is baselined at version 1 and this script does not run there
-- (spring.flyway.baseline-on-migrate, baseline-version: 1).

create table employee_interactions (
    id               bigint generated by default as identity,
    created_at       timestamp(6) not null,
    employee_email   varchar(255) not null,
    interaction_type varchar(50)  not null,
    visitor_id       varchar(255),
    primary key (id)
);

create table employee_likes (
    id             bigint generated by default as identity,
    created_at     timestamp(6) not null,
    employee_email varchar(255) not null,
    reaction_type  varchar(50)  not null,
    visitor_id     varchar(255),
    primary key (id)
);

create table page_visits (
    id         bigint generated by default as identity,
    created_at timestamp(6) not null,
    page_name  varchar(255) not null,
    visitor_id varchar(255),
    primary key (id)
);

create table search_logs (
    id            bigint generated by default as identity,
    created_at    timestamp(6) not null,
    query         varchar(255) not null,
    results_count integer      not null,
    visitor_id    varchar(255),
    primary key (id)
);
